/** Market colours that are not part of the MD3 scheme but are used by the cards. */
@Immutable
data class MarketColors(
    val up: Color,
    val down: Color,
    val flat: Color
)

val LocalMarketColors = staticCompositionLocalOf {
    MarketColors(up = UpLight, down = DownLight, flat = LightOnSurfaceVariant)
}

@Composable
fun FundRadarTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColors
        else -> LightColors
    }

    val market = if (darkTheme) {
        MarketColors(up = UpDark, down = DownDark, flat = DarkOnSurfaceVariant)
    } else {
        MarketColors(up = UpLight, down = DownLight, flat = LightOnSurfaceVariant)
    }

    CompositionLocalProvider(LocalMarketColors provides market) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = AppTypography,
            content = content
        )
    }
}
